const HOOK_CONTENT: &str = r#"# SysPilot hook — autogenerated by syspilot install
# Source this in your ~/.bashrc to enable logging:
#   source ~/.syspilot/syspilot.sh

if [ -n "$SYSPILOT_HOOK_LOADED" ]; then
    return
fi
export SYSPILOT_HOOK_LOADED=1

__syspilot_preexec() {
    echo "$(date +%s) $(pwd) $1" >> ~/.syspilot/command_start.log
}

__syspilot_precmd() {
    local exit_code=$?
    local last_cmd=$(history 1 | sed 's/^ *[0-9]* *//')
    echo "$(date -Iseconds) | $(pwd) | ${last_cmd} | ${exit_code}" >> ~/.syspilot/context.log
}

PROMPT_COMMAND="__syspilot_precmd; $PROMPT_COMMAND"
trap '__syspilot_preexec "$BASH_COMMAND"' DEBUG
"#;

pub fn user_binary_path() -> Result<PathBuf, String> {
    let home =
        dirs::home_dir().ok_or_else(|| "could not determine your home directory".to_string())?;
    Ok(home.join(".local").join("bin").join("syspilot"))
}

fn replace_binary(source: &std::path::Path, destination: &std::path::Path) -> io::Result<()> {
    let parent = destination
        .parent()
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "destination has no parent"))?;
    fs::create_dir_all(parent)?;
    let temporary = parent.join(format!(".syspilot-install-{}", std::process::id()));
    let result = (|| {
        fs::copy(source, &temporary)?;
        fs::set_permissions(&temporary, fs::Permissions::from_mode(0o755))?;
        fs::rename(&temporary, destination)
    })();
    if result.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    result
}

pub fn install_user_binary(force: bool) -> bool {
    let destination = match user_binary_path() {
        Ok(path) => path,
        Err(error) => {
            eprintln!("❌ {error}");
            return false;
        }
    };
    if destination.exists() && !force {
        println!(
            "⚠️  {} already exists. Run `syspilot install --binary --force` to replace it.",
            destination.display()
        );
        return true;
    }
    let source = match std::env::current_exe() {
        Ok(path) => path,
        Err(error) => {
            eprintln!("❌ Could not locate the running binary: {error}");
            return false;
        }
    };
    if let Err(error) = replace_binary(&source, &destination) {
        eprintln!(
            "❌ Could not install binary at {}: {error}",
            destination.display()
        );
        return false;
    }
    println!("✅ Installed binary at {}", destination.display());
    let bin_dir = destination
        .parent()
        .expect("binary destination has a parent");
    if !std::env::split_paths(&std::env::var_os("PATH").unwrap_or_default())
        .any(|entry| entry == bin_dir)
    {
        println!("Add this to your shell profile, then open a new terminal:");
        println!("  export PATH=\"$HOME/.local/bin:$PATH\"");
    }
    true
}

pub fn remove_user_binary() -> bool {
    let destination = match user_binary_path() {
        Ok(path) => path,
        Err(error) => {
            eprintln!("❌ {error}");
            return false;
        }
    };
    if !destination.exists() {
        println!(
            "No user-local SysPilot binary found at {}.",
            destination.display()
        );
        return true;
    }
    match fs::remove_file(&destination) {
        Ok(()) => {
            println!("Removed {}", destination.display());
            true
        }
        Err(error) => {
            eprintln!("❌ Could not remove {}: {error}", destination.display());
            false
        }
    }
}

pub fn install() -> bool {
    let dir = config::get_syspilot_dir();
    if let Err(error) = fs::create_dir_all(&dir) {
        eprintln!("❌ Could not create {}: {error}", dir.display());
        return false;
    }
    for name in ["session.log", "context.log", "command_start.log"] {
        let path = dir.join(name);
        if !path.exists() && fs::write(&path, "").is_err() {
            eprintln!("❌ Could not create {}", path.display());
            return false;
        }
    }
    let config_path = dir.join("config.json");
    if !config_path.exists() {
        if let Err(error) = config::save(&config::Config::default()) {
            eprintln!("❌ Could not create default configuration: {error}");
            return false;
        }
    }
    let hook_path = dir.join("syspilot.sh");
    if let Err(error) = fs::write(&hook_path, HOOK_CONTENT) {
        eprintln!("❌ Could not write {}: {error}", hook_path.display());
        return false;
    }
    println!("✅ SysPilot files are ready in {}", dir.display());
    println!("To capture failed shell commands, add this one line to your Bash profile:");
    println!("  source {}", hook_path.display());
    println!("The profile is not edited automatically.");
    println!("Optional: run `syspilot install --binary` to copy this binary to ~/.local/bin.");
    true
}

pub fn setup() -> bool {
    println!(
        "Welcome to SysPilot setup. You can change every setting later with `syspilot config`."
    );
    if !install() {
        return false;
    }
    let _ = install_user_binary(false);
    println!("\nChoose AI setup: [1] Gemini  [2] Ollama  [3] Skip for now");
    print!("Choice [3]: ");
    let _ = io::stdout().flush();
    let mut choice = String::new();
    let _ = io::stdin().read_line(&mut choice);
    let mut cfg = match config::load_checked() {
        Ok(cfg) => cfg,
        Err(error) => {
            eprintln!("❌ Could not load configuration: {error}");
            return false;
        }
    };
    match choice.trim() {
        "1" => { print!("Gemini API key: "); let _ = io::stdout().flush(); let mut key = String::new(); let _ = io::stdin().read_line(&mut key); if key.trim().is_empty() { println!("No key entered. Gemini was not configured."); } else { cfg.active_provider = "gemini".to_string(); cfg.gemini_api_key = key.trim().to_string(); } }
        "2" => { cfg.active_provider = "ollama".to_string(); print!("Ollama URL [{}]: ", cfg.ollama_url); let _ = io::stdout().flush(); let mut url = String::new(); let _ = io::stdin().read_line(&mut url); if !url.trim().is_empty() { cfg.ollama_url = url.trim().to_string(); } }
        _ => println!("AI setup skipped. Configure it later with `syspilot provider` and `syspilot config set-key`."),
    }
    if let Err(error) = config::save(&cfg) {
        eprintln!("❌ Could not save configuration: {error}");
        return false;
    }
    println!("\nNext steps:");
    println!("  1. source ~/.syspilot/syspilot.sh");
    println!("  2. syspilot status");
    println!("  3. syspilot explain --pid $$");
    println!("  4. syspilot --help");
    true
}

pub fn uninstall() -> bool {
    let hook_path = config::get_syspilot_dir().join("syspilot.sh");
    if hook_path.exists() {
        if let Err(error) = fs::remove_file(&hook_path) {
            eprintln!("❌ Could not remove {}: {error}", hook_path.display());
            return false;
        }
        println!("Removed hook script: {}", hook_path.display());
    }
    println!(
        "Your logs and configuration remain in {}.",
        config::get_syspilot_dir().display()
    );
    println!("Remove the source line from your shell profile. Use `syspilot uninstall --binary` to remove only the user-local binary.");
    true
}

pub fn status() -> bool {
    let dir = config::get_syspilot_dir();
    println!(
        "Version: {} ({})",
        env!("CARGO_PKG_VERSION"),
        env!("SYSPILOT_BUILD_COMMIT")
    );
    match std::env::current_exe() {
        Ok(path) => println!("Active binary: {}", path.display()),
        Err(error) => println!("⚠️  Active binary: unavailable ({error})"),
    }
    println!("SysPilot home: {}", dir.display());
    println!("Daemon socket: {}", config::daemon_socket_label());
    let hook = dir.join("syspilot.sh");
    println!(
        "{} shell hook: {}",
        if hook.exists() { "✅" } else { "⚠️" },
        if hook.exists() {
            "installed"
        } else {
            "not installed; run `syspilot install`"
        }
    );
    println!(
        "{} shell hook in this process",
        if std::env::var("SYSPILOT_HOOK_LOADED").is_ok() {
            "✅ active"
        } else {
            "⚠️ not active; run `source ~/.syspilot/syspilot.sh`"
        }
    );
    match user_binary_path() {
        Ok(path) if path.exists() => println!("✅ User-local binary: {}", path.display()),
        Ok(path) => println!("ℹ️  User-local binary not installed at {}", path.display()),
        Err(error) => println!("⚠️  {error}"),
    }
    match config::load_checked() {
        Ok(cfg) => {
            let model = match cfg.active_provider.as_str() {
                "gemini" => &cfg.gemini_model,
                "ollama" => &cfg.ollama_model,
                "syspilot" => &cfg.syspilot_model,
                _ => "unknown",
            };
            println!("✅ AI provider: {} (model {})", cfg.active_provider, model);
            println!(
                "{} Distributed telemetry",
                if cfg.distributed_telemetry.enabled {
                    "✅ enabled"
                } else {
                    "ℹ️  disabled"
                }
            );
        }
        Err(error) => println!("❌ Configuration error: {error}"),
    }
    match fs::metadata(config::daemon_health_path()).and_then(|meta| meta.modified()) {
        Ok(modified) => match SystemTime::now().duration_since(modified) {
            Ok(age) if age <= Duration::from_secs(3) => {
                println!("✅ Daemon heartbeat: fresh ({} ms ago)", age.as_millis())
            }
            Ok(age) => println!(
                "⚠️  Daemon heartbeat: stale ({} seconds ago)",
                age.as_secs()
            ),
            Err(_) => println!("⚠️  Daemon heartbeat timestamp is in the future"),
        },
        Err(_) => println!(
            "ℹ️  Daemon: not running. Start with `syspilot daemon` or install the systemd unit."
        ),
    }
    if let Ok(content) = fs::read_to_string(config::daemon_health_path()) {
        if let Ok(health) = serde_json::from_str::<serde_json::Value>(&content) {
            println!(
                "Netlink state: {}",
                health["netlink_state"].as_str().unwrap_or("unknown")
            );
            println!(
                "Dropped lifecycle events: {}",
                health["dropped_events"].as_u64().unwrap_or(0)
            );
            if let Some(exporter) = health["exporter"].as_object() {
                println!(
                    "Exporter: queued={} sent={} retried={} rejected={} dropped={} spool_bytes={} quarantined={} persistence_failures={}",
                    exporter.get("queued").and_then(|v| v.as_u64()).unwrap_or(0),
                    exporter.get("sent").and_then(|v| v.as_u64()).unwrap_or(0),
                    exporter
                        .get("retried")
                        .and_then(|v| v.as_u64())
                        .unwrap_or(0),
                    exporter
                        .get("rejected")
                        .and_then(|v| v.as_u64())
                        .unwrap_or(0),
                    exporter
                        .get("dropped")
                        .and_then(|v| v.as_u64())
                        .unwrap_or(0),
                    exporter.get("spool_bytes").and_then(|v| v.as_u64()).unwrap_or(0),
                    exporter.get("quarantined").and_then(|v| v.as_u64()).unwrap_or(0),
                    exporter.get("persistence_failures").and_then(|v| v.as_u64()).unwrap_or(0),
                );
                println!(
                    "Last telemetry acknowledgement: {}",
                    exporter
                        .get("last_acknowledgement_unix_nanos")
                        .and_then(|v| v.as_u64())
                        .map(|v| v.to_string())
                        .unwrap_or_else(|| "none".into())
                );
            } else {
                println!(
                    "Dropped telemetry messages: {}",
                    health["dropped_telemetry"].as_u64().unwrap_or(0)
                );
            }
        }
    }
    true
}

#[derive(Debug, Clone, Serialize)]
pub struct StatusDataV1 {
    pub version: String,
    pub build_commit: String,
    pub active_binary: Option<String>,
    pub syspilot_home: String,
    pub daemon_socket: String,
    pub shell_hook_installed: bool,
    pub shell_hook_active: bool,
    pub user_binary_installed: bool,
    pub active_provider: Option<String>,
    pub active_model: Option<String>,
    pub telemetry_enabled: Option<bool>,
    pub daemon: Option<HealthSnapshotV1>,
}

pub fn collect_status() -> AppResult<OutputEnvelopeV1<StatusDataV1>> {
    let dir = config::get_syspilot_dir();
    let mut diagnostics = Vec::new();
    let active_binary = match std::env::current_exe() {
        Ok(path) => Some(path.display().to_string()),
        Err(error) => {
            diagnostics.push(DiagnosticV1 {
                component: "active_binary".into(),
                state: CapabilityState::Unavailable,
                detail: error.to_string(),
                impact: "the running binary path cannot be verified".into(),
                recovery_command: None,
                fallback_used: None,
            });
            None
        }
    };
    let user_binary_installed = match user_binary_path() {
        Ok(path) => path.exists(),
        Err(error) => {
            diagnostics.push(DiagnosticV1 {
                component: "user_binary".into(),
                state: CapabilityState::Unavailable,
                detail: error,
                impact: "user-local installation cannot be verified".into(),
                recovery_command: Some("syspilot install --binary".into()),
                fallback_used: None,
            });
            false
        }
    };
    let (active_provider, active_model, telemetry_enabled) = match config::load_checked() {
        Ok(cfg) => {
            let model = match cfg.active_provider.as_str() {
                "gemini" => cfg.gemini_model,
                "ollama" => cfg.ollama_model,
                "syspilot" => cfg.syspilot_model,
                _ => "unknown".into(),
            };
            (
                Some(cfg.active_provider),
                Some(model),
                Some(cfg.distributed_telemetry.enabled),
            )
        }
        Err(error) => {
            diagnostics.push(DiagnosticV1 {
                component: "configuration".into(),
                state: CapabilityState::Misconfigured,
                detail: error.to_string(),
                impact: "configured features cannot be trusted".into(),
                recovery_command: Some("syspilot doctor".into()),
                fallback_used: None,
            });
            (None, None, None)
        }
    };
    let daemon = match crate::daemon_health::read(&config::daemon_health_path()) {
        Ok(snapshot) => Some(snapshot),
        Err(error) => {
            diagnostics.push(DiagnosticV1 {
                component: "daemon".into(),
                state: CapabilityState::Unavailable,
                detail: error.to_string(),
                impact: "live events are unavailable; local procfs diagnostics remain available"
                    .into(),
                recovery_command: Some("syspilot daemon".into()),
                fallback_used: Some("direct procfs diagnostics".into()),
            });
            None
        }
    };
    let outcome = if diagnostics
        .iter()
        .any(|item| item.state == CapabilityState::Misconfigured)
    {
        Outcome::Error
    } else if diagnostics.is_empty() {
        Outcome::Ok
    } else {
        Outcome::Degraded
    };
    OutputEnvelopeV1::new(
        "status",
        outcome,
        StatusDataV1 {
            version: env!("CARGO_PKG_VERSION").into(),
            build_commit: env!("SYSPILOT_BUILD_COMMIT").into(),
            active_binary,
            syspilot_home: dir.display().to_string(),
            daemon_socket: config::daemon_socket_label(),
            shell_hook_installed: dir.join("syspilot.sh").exists(),
            shell_hook_active: std::env::var("SYSPILOT_HOOK_LOADED").is_ok(),
            user_binary_installed,
            active_provider,
            active_model,
            telemetry_enabled,
            daemon,
        },
        diagnostics,
    )
}

#[cfg(test)]
mod tests {
    use super::replace_binary;
    use std::fs;
    use std::os::unix::fs::PermissionsExt;

    #[test]
    fn atomically_replaces_an_existing_binary() {
        let directory = tempfile::tempdir().unwrap();
        let source = directory.path().join("source");
        let destination = directory.path().join("bin").join("syspilot");
        fs::write(&source, b"new binary").unwrap();
        fs::create_dir_all(destination.parent().unwrap()).unwrap();
        fs::write(&destination, b"old binary").unwrap();
        replace_binary(&source, &destination).unwrap();
        assert_eq!(fs::read(&destination).unwrap(), b"new binary");
        assert_eq!(
            fs::metadata(&destination).unwrap().permissions().mode() & 0o777,
            0o755
        );
    }
}
